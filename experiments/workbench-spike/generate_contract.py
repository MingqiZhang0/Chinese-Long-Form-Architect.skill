"""Deterministic spike schema-to-C# generator. --check detects drift."""
import hashlib, json, re, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
path=ROOT/'docs/workbench/contracts/workbench-wire.schema.json'
schema=json.loads(path.read_text(encoding='utf-8')); defs=schema['$defs']
def pascal(s): return ''.join(x[:1].upper()+x[1:] for x in s.split('_'))
def typ(s):
    if '$ref' in s: return s['$ref'].split('/')[-1] if s['$ref'].split('/')[-1] != 'Version' else 'string'
    if 'anyOf' in s: return typ(next(x for x in s['anyOf'] if x.get('type')!='null'))+'?'
    return {'string':'string','integer':'int','number':'double','boolean':'bool','array': 'IReadOnlyList<'+typ(s['items'])+'>' if s.get('type')=='array' else '', 'object':'JsonElement'}.get(s.get('type'),'string')
out=['// Generated by generate_contract.py; do not edit.','using System.Text.Json;','using System.Text.Json.Serialization;','namespace Workbench.Protocol;']
for name,s in defs.items():
    if 'x-id-type' in s:
        out += [f'[JsonConverter(typeof(IdConverter<{name}>))]',f'public readonly record struct {name}(string Value) : IWireId<{name}> {{ public static {name} Create(string value) => new(value); public override string ToString() => Value; }}']
    elif 'enum' in s:
        out += [f'public enum {name} {{ '+', '.join(s['enum'])+' }']
    elif s.get('type')=='object':
        props=[]
        for p,v in s['properties'].items():
            optional=p not in s.get('required',[])
            t=typ(v)
            if optional and not t.endswith('?'):t+='?'
            attribute=f'[property: JsonPropertyName("{p}")]'+(' [property: JsonIgnore(Condition=JsonIgnoreCondition.WhenWritingNull)]' if optional else '')
            props.append(f'{attribute} {t} {pascal(p) if pascal(p)!=name else pascal(p)+"Status"}')
        out += [f'public sealed record {name}(\n    '+',\n    '.join(props)+') { [JsonExtensionData] public Dictionary<string, JsonElement>? Extensions {get;init;} }']
out += [f'public static class ContractIdentity {{ public const string Digest = "sha256:{hashlib.sha256(path.read_bytes()).hexdigest()}"; }}']
target=ROOT/'experiments/workbench-spike/desktop/Workbench.Protocol/Generated.cs'
content='\n'.join(out)+'\n'
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != content: raise SystemExit('Generated contract drift')
else: target.write_text(content,encoding='utf-8')
